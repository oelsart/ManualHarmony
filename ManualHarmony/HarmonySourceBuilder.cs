using System.Collections.Immutable;
using System.Diagnostics.CodeAnalysis;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace ManualHarmony;

internal static class HarmonySourceBuilder
{
  private static readonly SymbolDisplayFormat FullyQualifiedFormat = SymbolDisplayFormat.FullyQualifiedFormat;

  public static string Build(ImmutableArray<INamedTypeSymbol> patchTypes, AnalyzerConfigOptionsProvider optionsProvider)
  {
    var namespaceName = GetBuildProperty(optionsProvider, "ManualHarmony_GeneratedNamespace")
                        ?? "ManualHarmony.Generated";
    var className = GetBuildProperty(optionsProvider, "ManualHarmony_GeneratedClassName")
                    ?? "ManualHarmonyPatches";
    var types = patchTypes.Distinct(SymbolEqualityComparer.Default).OfType<INamedTypeSymbol>().ToArray();
    var builder = new StringBuilder();

    builder.AppendLine("// <auto-generated />");
    builder.AppendLine("#nullable enable");
    builder.AppendLine("using System;");
    builder.AppendLine("using System.Collections.Generic;");
    builder.AppendLine("using System.Linq;");
    builder.AppendLine("using System.Reflection;");
    builder.AppendLine("using HarmonyLib;");
    builder.AppendLine("using ManualHarmony.Runtime;");
    builder.AppendLine($"namespace {namespaceName};");
    builder.AppendLine($"public sealed class {className} : IManualPatches");
    builder.AppendLine("{");

    var generatedTypes = types.Select((type, index) => new GeneratedType(type, index)).ToArray();
    foreach (var generatedType in generatedTypes)
      AppendFields(builder, generatedType);

    AppendPublicApi(builder, generatedTypes);

    foreach (var generatedType in generatedTypes)
      AppendPatchMethods(builder, generatedType);

    AppendSharedHelpers(builder);
    builder.AppendLine("}");
    return builder.ToString();
  }

  private static void AppendFields(StringBuilder builder, GeneratedType generatedType)
  {
    var patchType = generatedType.Symbol;
    var typeName = GetTypeName(patchType);

    foreach (var part in generatedType.PatchParts)
    {
      AppendMethodInfoField(builder, part.Method, part.MethodField);
      AppendMetadataFields(builder, part.MethodField, part.Metadata);
      if (generatedType.TargetMethodsMethod is null && generatedType.TargetMethodMethod is null)
      {
        if (part.Target is { } partTarget)
          AppendTargetField(builder, partTarget, part.TargetField, patchType);
        else
          builder.AppendLine($"private static MethodBase? {TargetAccessorName(part.TargetField)}() => null;");
      }
    }

    if (generatedType.PrepareMethod is not null)
      AppendDelegateField(builder, generatedType.PrepareMethod, generatedType.PrepareField);
    if (generatedType.TargetMethodsMethod is not null)
      AppendDelegateField(builder, generatedType.TargetMethodsMethod, generatedType.TargetMethodsField);
    if (generatedType.TargetMethodMethod is not null)
      AppendDelegateField(builder, generatedType.TargetMethodMethod, generatedType.TargetMethodField);

    if (generatedType.Target is { } target)
      AppendTargetField(builder, target, generatedType.TargetField, patchType);
    else if (generatedType.TargetMethodsMethod is null && generatedType.TargetMethodMethod is null)
      builder.AppendLine($"private static MethodBase? {TargetAccessorName(generatedType.TargetField)}() => null;");

    foreach (var reversePatch in generatedType.ReversePatches)
    {
      AppendMethodInfoField(builder, reversePatch.Method, reversePatch.MethodField);
      AppendMetadataFields(builder, reversePatch.MethodField, reversePatch.Metadata);
      if (reversePatch.Target is { } reverseTarget)
        AppendTargetField(builder, reverseTarget, reverseTarget.FieldName, patchType);
    }

    _ = typeName;
  }

  private static void AppendPublicApi(StringBuilder builder, GeneratedType[] types)
  {
    var categories = types.Select(type => type.Category)
      .Where(category => category.Length > 0)
      .Distinct(StringComparer.Ordinal)
      .ToArray();
    builder.AppendLine("private static readonly IReadOnlyList<string> GeneratedPatchCategories = Array.AsReadOnly(new string[]");
    builder.AppendLine("{");
    foreach (var category in categories)
      builder.AppendLine($"    {Literal(category)},");
    builder.AppendLine("});");
    builder.AppendLine("public IReadOnlyList<string> PatchCategories => GeneratedPatchCategories;");

    builder.AppendLine("""
                       public void PatchAll(Harmony harmony, ManualPatchOptions? options = null)
                       {
                           var patchOptions = options ?? ManualPatchOptions.Default;
                       """);
    foreach (var type in types)
      builder.AppendLine($"    Patch_{type.Index}(harmony, patchOptions);");
    builder.AppendLine("}");

    builder.AppendLine("""
                       public void UnpatchAll(Harmony harmony, ManualPatchOptions? options = null)
                       {
                           var patchOptions = options ?? ManualPatchOptions.Default;
                       """);
    foreach (var type in types)
      builder.AppendLine($"    Unpatch_{type.Index}(harmony, patchOptions);");
    builder.AppendLine("}");

    builder.AppendLine("""
                       public void PatchCategory(Harmony harmony, string category,
                           ManualPatchOptions? options = null)
                       {
                           var patchOptions = options ?? ManualPatchOptions.Default;
                       """);
    foreach (var categoryGroup in types.GroupBy(type => type.Category))
    {
      builder.AppendLine($"    if (category == {Literal(categoryGroup.Key)})");
      builder.AppendLine("    {");
      foreach (var type in categoryGroup)
        builder.AppendLine($"        Patch_{type.Index}(harmony, patchOptions);");
      builder.AppendLine("    }");
    }
    builder.AppendLine("}");

    builder.AppendLine("""
                       public void UnpatchCategory(Harmony harmony, string category,
                           ManualPatchOptions? options = null)
                       {
                           var patchOptions = options ?? ManualPatchOptions.Default;
                       """);
    foreach (var categoryGroup in types.GroupBy(type => type.Category))
    {
      builder.AppendLine($"    if (category == {Literal(categoryGroup.Key)})");
      builder.AppendLine("    {");
      foreach (var type in categoryGroup)
        builder.AppendLine($"        Unpatch_{type.Index}(harmony, patchOptions);");
      builder.AppendLine("    }");
    }
    builder.AppendLine("}");

    builder.AppendLine("""
                       public void PatchUncategorized(Harmony harmony, ManualPatchOptions? options = null)
                           => PatchCategory(harmony, "", options);

                       public void UnpatchUncategorized(Harmony harmony, ManualPatchOptions? options = null)
                           => UnpatchCategory(harmony, "", options);
                       """);
  }

  private static void AppendPatchMethods(StringBuilder builder, GeneratedType generatedType)
  {
    var index = generatedType.Index;
    var patchType = generatedType.Symbol;
    var category = Literal(generatedType.Category);
    var patchTypeName = GetTypeName(patchType);

    AppendOperation(builder, "Patch", generatedType);
    builder.AppendLine($"private static void PatchCore_{index}(Harmony harmony, ManualPatchOptions options)");
    builder.AppendLine("{");

    if (generatedType.PrepareMethod is not null)
      builder.AppendLine($"    if (!{generatedType.PrepareField}()) return;");

    foreach (var reversePatch in generatedType.ReversePatches)
    {
      var targetExpression = reversePatch.Target is null
        ? generatedType.TargetMethodsMethod is not null
          ? $"{generatedType.TargetMethodsField}().FirstOrDefault()"
          : generatedType.TargetMethodMethod is not null
            ? $"{generatedType.TargetMethodField}()"
            : generatedType.Target is not null
                ? $"{TargetAccessorName(generatedType.TargetField)}()"
              : "null"
        : $"{TargetAccessorName(reversePatch.Target.FieldName)}()";
      builder.AppendLine($"    var reverseOriginal_{reversePatch.Index} = {targetExpression};");
      AppendCreateHarmonyMethod(builder, generatedType, reversePatch.MethodField, "ReversePatch",
        reversePatch.Metadata, $"reverseOriginal_{reversePatch.Index}", category, $"reverseMethod_{reversePatch.Index}");
      builder.AppendLine($"    if (reverseMethod_{reversePatch.Index} is not null)");
      var reversePatchType = $"HarmonyReversePatchType.{reversePatch.Metadata.ReversePatchType ?? "Original"}";
      builder.AppendLine($"        harmony.CreateReversePatcher(reverseOriginal_{reversePatch.Index}, reverseMethod_{reversePatch.Index})");
      builder.AppendLine($"            .Patch(GetReversePatchType(reverseOriginal_{reversePatch.Index},");
      builder.AppendLine($"                {reversePatchType}));");
    }

    if (generatedType.PatchParts.Count == 0)
    {
      builder.AppendLine("    return;");
    }
    else if (generatedType.TargetMethodsMethod is not null)
    {
      builder.AppendLine($"    foreach (var targetCandidate in {generatedType.TargetMethodsField}())");
      builder.AppendLine("    {");
      builder.AppendLine("        var original = targetCandidate;");
      AppendApplyParts(builder, generatedType, "original", category, patchTypeName, "        ");
      builder.AppendLine("    }");
    }
    else
    {
      foreach (var part in generatedType.PatchParts)
      {
        var targetExpression = generatedType.TargetMethodMethod is not null
          ? $"{generatedType.TargetMethodField}()"
          : $"{TargetAccessorName(part.TargetField)}()";
        builder.AppendLine("    {");
        builder.AppendLine($"        var original = {targetExpression};");
        AppendApplyParts(builder, generatedType, "original", category, patchTypeName, "        ", [part]);
        builder.AppendLine("    }");
      }
    }

    builder.AppendLine("}");
    AppendUnpatchOperation(builder, generatedType);

    builder.AppendLine($"private static void UnpatchCore_{index}(Harmony harmony, ManualPatchOptions options)");
    builder.AppendLine("{");
    if (generatedType.PatchParts.Count == 0)
    {
      builder.AppendLine("    return;");
    }
    else if (generatedType.TargetMethodsMethod is not null)
    {
      builder.AppendLine($"    foreach (var targetCandidate in {generatedType.TargetMethodsField}())");
      builder.AppendLine("    {");
      builder.AppendLine("        var original = targetCandidate;");
      AppendUnpatchParts(builder, generatedType, "original", category, patchTypeName, "        ");
      builder.AppendLine("    }");
    }
    else
    {
      foreach (var part in generatedType.PatchParts)
      {
        var targetExpression = generatedType.TargetMethodMethod is not null
          ? $"{generatedType.TargetMethodField}()"
          : $"{TargetAccessorName(part.TargetField)}()";
        builder.AppendLine("    {");
        builder.AppendLine($"        var original = {targetExpression};");
        AppendUnpatchParts(builder, generatedType, "original", category, patchTypeName, "        ", [part]);
        builder.AppendLine("    }");
      }
    }
    builder.AppendLine("}");
  }

  private static void AppendApplyParts(StringBuilder builder, GeneratedType generatedType, string original,
    string category, string patchTypeName, string indent, IReadOnlyList<PatchPart>? patchParts = null)
  {
    patchParts ??= generatedType.PatchParts;
    builder.AppendLine($"{indent}var processor = harmony.CreateProcessor({original});");
    foreach (var part in patchParts)
      AppendCreateHarmonyMethod(builder, generatedType, part.MethodField, part.Kind, part.Metadata,
        original, category, part.Kind, indent);

    foreach (var part in patchParts)
    {
      var addMethod = part.Kind switch
      {
        "Prefix" => "AddPrefix",
        "Postfix" => "AddPostfix",
        "Transpiler" => "AddTranspiler",
        "Finalizer" => "AddFinalizer",
        "InnerPrefix" => "AddInnerPrefix",
        "InnerPostfix" => "AddInnerPostfix",
        "InnerFinalizer" => "AddInnerFinalizer",
        _ => null
      };
      if (addMethod is not null)
        builder.AppendLine($"{indent}if ({part.Kind} is not null) processor.{addMethod}({part.Kind});");
    }
    builder.AppendLine($"{indent}processor.Patch();");
    _ = patchTypeName;
  }

  private static void AppendUnpatchParts(StringBuilder builder, GeneratedType generatedType, string original,
    string category, string patchTypeName, string indent, IReadOnlyList<PatchPart>? patchParts = null)
  {
    patchParts ??= generatedType.PatchParts;
    foreach (var part in patchParts)
    {
      builder.AppendLine($"{indent}if (ShouldUnpatch(options, typeof({patchTypeName}), {original}, {part.MethodField}, HarmonyPatchType.{part.Kind}, {category}))");
      builder.AppendLine($"{indent}    harmony.Unpatch({original}, {part.MethodField});");
    }
  }

  private static void AppendOperation(StringBuilder builder, string operation, GeneratedType generatedType)
  {
    var index = generatedType.Index;
    builder.AppendLine($"private static void {operation}_{index}(Harmony harmony, ManualPatchOptions options)");
    builder.AppendLine("{");
    builder.AppendLine("    if (!options.EnableTryCatch)");
    builder.AppendLine("    {");
    builder.AppendLine($"        {operation}Core_{index}(harmony, options);");
    builder.AppendLine("        return;");
    builder.AppendLine("    }");
    builder.AppendLine("    try");
    builder.AppendLine("    {");
    builder.AppendLine($"        {operation}Core_{index}(harmony, options);");
    builder.AppendLine("    }");
    builder.AppendLine("    catch (Exception ex)");
    builder.AppendLine("    {");
    builder.AppendLine("        if (options.Logger is null) throw;");
    builder.AppendLine("        options.Logger(ex);");
    builder.AppendLine("    }");
    builder.AppendLine("}");
  }

  private static void AppendUnpatchOperation(StringBuilder builder, GeneratedType generatedType)
  {
    AppendOperation(builder, "Unpatch", generatedType);
  }

  private static void AppendCreateHarmonyMethod(StringBuilder builder, GeneratedType generatedType, string methodField,
    string kind, PatchMetadata metadata, string original, string category, string variableName, string indent = "    ")
  {
    var patchTypeName = GetTypeName(generatedType.Symbol);
    var priority = metadata.Priority?.ToString(System.Globalization.CultureInfo.InvariantCulture) ?? "null";
    var before = StringArrayFieldExpression(methodField, "Before", metadata.Before);
    var after = StringArrayFieldExpression(methodField, "After", metadata.After);
    var reversePatchType = metadata.ReversePatchType is null
      ? "null"
      : $"HarmonyReversePatchType.{metadata.ReversePatchType}";

    builder.AppendLine($"{indent}var {variableName} = CreateHarmonyMethod(options, typeof({patchTypeName}), {original}, {methodField}, HarmonyPatchType.{kind}, {category}, {priority}, {before}, {after}, {reversePatchType});");
  }

  private static void AppendSharedHelpers(StringBuilder builder)
  {
    builder.AppendLine("""
                       private static HarmonyMethod? CreateHarmonyMethod(ManualPatchOptions options, Type patchType,
                           MethodBase? original, MethodInfo patchMethod, HarmonyPatchType patchKind, string category,
                           int? priority, string[]? before, string[]? after,
                           HarmonyReversePatchType? reversePatchType)
                       {
                           if (options.ShouldPatch is not null &&
                               !options.ShouldPatch(new ManualPatchContext(patchType, original, patchMethod, patchKind, category)))
                               return null;

                           var method = new HarmonyMethod(patchMethod);
                           if (priority.HasValue) method.priority = priority.Value;
                           if (before is { Length: > 0 }) method.before = before;
                           if (after is { Length: > 0 }) method.after = after;
                           if (reversePatchType.HasValue) method.reversePatchType = reversePatchType;
                           return method;
                       }

                       private static bool ShouldUnpatch(ManualPatchOptions options, Type patchType,
                           MethodBase? original, MethodInfo patchMethod, HarmonyPatchType patchKind, string category)
                       {
                           return options.ShouldUnpatch is null ||
                                  options.ShouldUnpatch(new ManualPatchContext(patchType, original, patchMethod, patchKind, category));
                       }

                       private static HarmonyReversePatchType GetReversePatchType(MethodBase? original,
                           HarmonyReversePatchType reversePatchType)
                       {
                           return reversePatchType == HarmonyReversePatchType.Snapshot && original is not null &&
                                  Harmony.GetPatchInfo(original) is null
                               ? HarmonyReversePatchType.Original
                               : reversePatchType;
                       }

                       private static MethodInfo GetStaticMethod(Type type, string name, Type[] parameterTypes)
                       {
                           return type.GetMethods(BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic)
                               .First(method => method.Name == name &&
                                   method.GetParameters().Select(parameter => parameter.ParameterType).SequenceEqual(parameterTypes));
                       }

                       private static MethodBase? ResolveAnnotatedTarget(Type type, string? methodName,
                           MethodType methodType, Type[]? argumentTypes)
                       {
                           switch (methodType)
                           {
                               case MethodType.Normal:
                                   return string.IsNullOrEmpty(methodName) ? null : AccessTools.DeclaredMethod(type, methodName, argumentTypes);
                               case MethodType.Getter:
                                   return string.IsNullOrEmpty(methodName)
                                       ? AccessTools.DeclaredIndexerGetter(type, argumentTypes)
                                       : AccessTools.DeclaredPropertyGetter(type, methodName);
                               case MethodType.Setter:
                                   return string.IsNullOrEmpty(methodName)
                                       ? AccessTools.DeclaredIndexerSetter(type, argumentTypes)
                                       : AccessTools.DeclaredPropertySetter(type, methodName);
                               case MethodType.Constructor:
                                   return AccessTools.DeclaredConstructor(type, argumentTypes);
                               case MethodType.StaticConstructor:
                                   return AccessTools.GetDeclaredConstructors(type).FirstOrDefault(method => method.IsStatic);
                               case MethodType.Enumerator:
                                   var enumeratorMethod = string.IsNullOrEmpty(methodName)
                                       ? null
                                       : AccessTools.DeclaredMethod(type, methodName, argumentTypes);
                                   return enumeratorMethod is null ? null : AccessTools.EnumeratorMoveNext(enumeratorMethod);
                               case MethodType.Async:
                                   var asyncMethod = string.IsNullOrEmpty(methodName)
                                       ? null
                                       : AccessTools.DeclaredMethod(type, methodName, argumentTypes);
                                   return asyncMethod is null ? null : AccessTools.AsyncMoveNext(asyncMethod);
                               case MethodType.Finalizer:
                                   return AccessTools.DeclaredFinalizer(type);
                               case MethodType.EventAdd:
                                   return string.IsNullOrEmpty(methodName) ? null : AccessTools.DeclaredEventAdder(type, methodName);
                               case MethodType.EventRemove:
                                   return string.IsNullOrEmpty(methodName) ? null : AccessTools.DeclaredEventRemover(type, methodName);
                           }

                           var typeName = methodType.ToString();
                           return typeName.StartsWith("Operator", StringComparison.Ordinal)
                               ? AccessTools.DeclaredMethod(type, "op_" + typeName["Operator".Length..], argumentTypes)
                               : null;
                       }

                       private static MethodBase? ResolveAnnotatedTarget(string typeName, string? methodName,
                           MethodType methodType, Type[]? argumentTypes)
                       {
                           var type = AccessTools.TypeByName(typeName);
                           return type is null ? null : ResolveAnnotatedTarget(type, methodName, methodType, argumentTypes);
                       }
                       """);
  }

  private static void AppendTargetField(StringBuilder builder, HarmonyTarget target, string fieldName,
    INamedTypeSymbol patchType)
  {
    if (target is { DeclaringType: INamedTypeSymbol declaringType, MethodType: "Normal", MethodName: not null } &&
        target.ArgumentVariations.IsDefaultOrEmpty &&
        TryFindTargetMethod(declaringType, target, out var method) &&
        CanUseMethodGroup(method, patchType))
    {
      var methodInfoField = fieldName + "_MethodInfo";
      AppendMethodInfoField(builder, method, methodInfoField);
      builder.AppendLine($"private static MethodBase? {TargetAccessorName(fieldName)}() => {methodInfoField};");
      return;
    }

    var declaringTypeExpression = target.DeclaringType is not null
      ? $"typeof({GetTypeName(target.DeclaringType)})"
      : "null";
    var argumentExpressions = target.ArgumentTypes.IsDefaultOrEmpty
      ? null
      : target.ArgumentTypes.Select((type, index) =>
        ArgumentTypeExpression(type, index, target.ArgumentVariations));
    var arguments = argumentExpressions is null
      ? "null"
      : $"new Type[] {{ {string.Join(", ", argumentExpressions)} }}";
    var resolver = target.DeclaringType is null
      ? "null"
      : $"ResolveAnnotatedTarget({declaringTypeExpression}, {NullableLiteral(target.MethodName)}, MethodType.{target.MethodType}, {arguments})";
    if (target.TypeName is not null)
      resolver = $"ResolveAnnotatedTarget({Literal(target.TypeName)}, {NullableLiteral(target.MethodName)}, MethodType.{target.MethodType}, {arguments})";
    builder.AppendLine($"private static MethodBase? {TargetAccessorName(fieldName)}() => {resolver};");
  }

  private static string TargetAccessorName(string fieldName) => $"Get_{fieldName}";

  private static string ArgumentTypeExpression(ITypeSymbol type, int index,
    ImmutableArray<string> variations)
  {
    var typeExpression = $"typeof({GetTypeName(type)})";
    if (variations.IsDefaultOrEmpty || index >= variations.Length)
      return typeExpression;

    return variations[index] switch
    {
      "Ref" or "Out" => $"{typeExpression}.MakeByRefType()",
      "Pointer" => $"{typeExpression}.MakePointerType()",
      _ => typeExpression
    };
  }

  private static void AppendDelegateField(StringBuilder builder, IMethodSymbol method, string fieldName)
  {
    var delegateName = fieldName + "_Delegate";
    AppendDelegateType(builder, method, delegateName);
    var methodAccess = CanUseMethodGroup(method, method.ContainingType) ? MethodGroup(method) : null;
    var methodTypes = ParameterTypeArray(method);
    var initializer = methodAccess is not null
      ? $"({delegateName}){methodAccess}"
      : $"({delegateName})Delegate.CreateDelegate(typeof({delegateName}), GetStaticMethod(typeof({GetTypeName(method.ContainingType)}), {Literal(method.Name)}, {methodTypes}))";
    builder.AppendLine($"private static readonly {delegateName} {fieldName} = {initializer};");
  }

  private static void AppendMethodInfoField(StringBuilder builder, IMethodSymbol method, string fieldName)
  {
    if (CanUseMethodGroup(method, method.ContainingType))
    {
      var delegateName = fieldName + "_Delegate";
      AppendDelegateType(builder, method, delegateName);
      builder.AppendLine($"private static readonly MethodInfo {fieldName} = (({delegateName}){MethodGroup(method)}).Method;");
      return;
    }

    builder.AppendLine($"private static readonly MethodInfo {fieldName} = GetStaticMethod(typeof({GetTypeName(method.ContainingType)}), {Literal(method.Name)}, {ParameterTypeArray(method)});");
  }

  private static string ParameterTypeArray(IMethodSymbol method)
  {
    if (method.Parameters.Length == 0)
      return "Type.EmptyTypes";

    var parameterTypes = method.Parameters.Select(parameter =>
    {
      var typeName = GetTypeName(parameter.Type.WithNullableAnnotation(NullableAnnotation.NotAnnotated));
      var type = $"typeof({typeName})";
      return parameter.RefKind == RefKind.None ? type : $"{type}.MakeByRefType()";
    });
    return $"new Type[] {{ {string.Join(", ", parameterTypes)} }}";
  }

  private static void AppendDelegateType(StringBuilder builder, IMethodSymbol method, string delegateName)
  {
    var returnType = GetTypeName(method.ReturnType);
    if (method.ReturnsByRef)
      returnType = "ref " + returnType;
    else if (method.ReturnsByRefReadonly)
      returnType = "ref readonly " + returnType;

    var parameters = method.Parameters.Select((parameter, index) =>
    {
      var modifier = parameter.RefKind switch
      {
        RefKind.Ref => "ref ",
        RefKind.Out => "out ",
        RefKind.In => "in ",
        _ => ""
      };
      return $"{modifier}{GetTypeName(parameter.Type)} __arg{index}";
    });

    builder.AppendLine($"private delegate {returnType} {delegateName}({string.Join(", ", parameters)});");
  }

  private static bool CanUseMethodGroup(IMethodSymbol method, ISymbol fromSymbol)
  {
    if (!method.IsStatic || method.IsGenericMethod || method.IsVararg ||
        method.ExplicitInterfaceImplementations.Length > 0 ||
        method.ReturnType.TypeKind is TypeKind.Pointer or TypeKind.FunctionPointer ||
        method.Parameters.Any(parameter => parameter.Type.TypeKind is TypeKind.Pointer or TypeKind.FunctionPointer))
      return false;

    var sameAssembly = SymbolEqualityComparer.Default.Equals(method.ContainingAssembly, fromSymbol.ContainingAssembly);
    var accessibility = method.DeclaredAccessibility;
    return accessibility == Accessibility.Public ||
           sameAssembly && accessibility is Accessibility.Internal or Accessibility.ProtectedOrInternal;
  }

  private static string MethodGroup(IMethodSymbol method)
  {
    return $"{GetTypeName(method.ContainingType)}.{EscapeIdentifier(method.Name)}";
  }

  private static bool TryFindTargetMethod(INamedTypeSymbol targetType, HarmonyTarget target,
	  [MaybeNullWhen(false)] out IMethodSymbol method)
  {
    var methods = targetType.GetMembers(target.MethodName!)
      .OfType<IMethodSymbol>()
      .Where(candidate => !candidate.IsGenericMethod);

    if (!target.ArgumentTypes.IsDefault)
      methods = methods.Where(candidate =>
        candidate.Parameters.Length == target.ArgumentTypes.Length &&
        candidate.Parameters.Select((parameter, index) =>
          SymbolEqualityComparer.Default.Equals(parameter.Type, target.ArgumentTypes[index])).All(matches => matches));
    else
    {
      var candidates = methods.ToArray();
      if (candidates.Length != 1)
      {
        method = null;
        return false;
      }

      method = candidates[0];
      return true;
    }

    method = methods.FirstOrDefault();
    return method is not null;
  }

  private static string? GetBuildProperty(AnalyzerConfigOptionsProvider optionsProvider, string name)
  {
    return optionsProvider.GlobalOptions.TryGetValue($"build_property.{name}", out var value) ? value : null;
  }

  private static string GetTypeName(ITypeSymbol symbol) => symbol.ToDisplayString(FullyQualifiedFormat);

  private static string EscapeIdentifier(string value)
  {
    return SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None ||
           SyntaxFacts.GetContextualKeywordKind(value) != SyntaxKind.None
      ? "@" + value
      : value;
  }

  private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

  private static string NullableLiteral(string? value) => value is null ? "null" : Literal(value);

  private static void AppendMetadataFields(StringBuilder builder, string methodField, PatchMetadata metadata)
  {
    if (!metadata.Before.IsDefaultOrEmpty)
      builder.AppendLine($"private static readonly string[] {methodField}_Before = {StringArrayExpression(metadata.Before)};");
    if (!metadata.After.IsDefaultOrEmpty)
      builder.AppendLine($"private static readonly string[] {methodField}_After = {StringArrayExpression(metadata.After)};");
  }

  private static string StringArrayExpression(ImmutableArray<string> values)
  {
    return $"new string[] {{ {string.Join(", ", values.Select(Literal))} }}";
  }

  private static string StringArrayFieldExpression(string methodField, string suffix, ImmutableArray<string> values)
  {
    return values.IsDefaultOrEmpty ? "null" : $"{methodField}_{suffix}";
  }

  private static string GetCategory(INamedTypeSymbol patchType)
  {
    foreach (var attribute in patchType.GetAttributes())
    {
      if (attribute.AttributeClass?.ToDisplayString() == HarmonySymbolNames.HarmonyPatchCategory &&
          attribute.ConstructorArguments.FirstOrDefault().Value is string category)
        return category;
    }

    return "";
  }

  private sealed class GeneratedType
  {
    public GeneratedType(INamedTypeSymbol symbol, int index)
    {
      Symbol = symbol;
      Index = index;
      Category = GetCategory(symbol);

      var methods = symbol.GetMembers().OfType<IMethodSymbol>().Where(method => method.IsStatic).ToArray();
      var recognizedKinds = new[] { "Prefix", "Postfix", "Transpiler", "Finalizer", "InnerPrefix", "InnerPostfix", "InnerFinalizer" };
      var parts = new List<PatchPart>();
      foreach (var kind in recognizedKinds)
      {
        var method = methods.FirstOrDefault(candidate => candidate.Name == kind);
        if (method is not null)
          parts.Add(new PatchPart(method, kind, $"PatchMethod_{index}_{kind}", ReadMetadata(symbol, method),
            ReadTarget(symbol, method), $"Target_{index}_{kind}"));
      }

      PatchParts = parts;
      var reverseMethods = methods.Where(method => method.GetAttributes()
        .Any(attribute => attribute.AttributeClass?.ToDisplayString() == HarmonySymbolNames.HarmonyReversePatch));
      ReversePatches =
      [
	      .. reverseMethods.Select((method, reverseIndex) =>
	      {
		      var target = ReadTarget(symbol, method);
		      var reverseType = ReadReversePatchType(method);
		      var metadata = ReadMetadata(symbol, method) with { ReversePatchType = reverseType };
		      return new ReversePatchPart(method, reverseIndex, $"ReverseMethod_{index}_{reverseIndex}",
			      target is null ? null : target with { FieldName = $"ReverseTarget_{index}_{reverseIndex}" }, metadata);
	      })
      ];

      PrepareMethod = methods.FirstOrDefault(method => method.Name == "Prepare" &&
        method.Parameters.Length == 0 && method.ReturnType.SpecialType == SpecialType.System_Boolean);
      TargetMethodsMethod = methods.FirstOrDefault(method => method.Name == "TargetMethods" &&
        method.Parameters.Length == 0 && method.ReturnType.AllInterfaces.Concat([method.ReturnType])
          .Any(type => type.ToDisplayString() == "System.Collections.Generic.IEnumerable<HarmonyLib.MethodBase>" ||
                       type.ToDisplayString() == "System.Collections.Generic.IEnumerable<System.Reflection.MethodBase>"));
      TargetMethodMethod = TargetMethodsMethod is null
        ? methods.FirstOrDefault(method => method.Name == "TargetMethod" && method.Parameters.Length == 0 &&
          method.ReturnType.ToDisplayString() is "System.Reflection.MethodBase" or "System.Reflection.MethodInfo")
        : null;

      PrepareField = $"Prepare_{index}";
      TargetMethodsField = $"TargetMethods_{index}";
      TargetMethodField = $"TargetMethod_{index}";
      Target = TargetMethodsMethod is null && TargetMethodMethod is null
        ? ReadTarget(symbol, null)
        : null;
      TargetField = $"Target_{index}";
    }

    public INamedTypeSymbol Symbol { get; }
    public int Index { get; }
    public string Category { get; }
    public List<PatchPart> PatchParts { get; }
    public ReversePatchPart[] ReversePatches { get; }
    public IMethodSymbol? PrepareMethod { get; }
    public IMethodSymbol? TargetMethodsMethod { get; }
    public IMethodSymbol? TargetMethodMethod { get; }
    public string PrepareField { get; }
    public string TargetMethodsField { get; }
    public string TargetMethodField { get; }
    public HarmonyTarget? Target { get; }
    public string TargetField { get; }
  }

  private sealed record PatchPart(IMethodSymbol Method, string Kind, string MethodField, PatchMetadata Metadata,
    HarmonyTarget? Target, string TargetField);
  
  private sealed record ReversePatchPart(IMethodSymbol Method, int Index, string MethodField, HarmonyTarget? Target,
    PatchMetadata Metadata);
  
  private sealed record HarmonyTarget(ITypeSymbol? DeclaringType, string? TypeName, string? MethodName,
    string MethodType, ImmutableArray<ITypeSymbol> ArgumentTypes, ImmutableArray<string> ArgumentVariations,
    string FieldName = "");
  
  private sealed record PatchMetadata(int? Priority, ImmutableArray<string> Before, ImmutableArray<string> After,
    string? ReversePatchType = null);

  private static HarmonyTarget? ReadTarget(INamedTypeSymbol patchType, IMethodSymbol? method)
  {
    var result = new MutableTarget();
    foreach (var attribute in patchType.GetAttributes().Concat(method?.GetAttributes() ?? ImmutableArray<AttributeData>.Empty))
    {
      if (attribute.AttributeClass?.ToDisplayString() != HarmonySymbolNames.HarmonyPatch ||
          attribute.AttributeConstructor is null)
        continue;

      for (var index = 0; index < attribute.ConstructorArguments.Length; index++)
      {
        var argument = attribute.ConstructorArguments[index];
        var parameterName = attribute.AttributeConstructor.Parameters[index].Name;
        switch (parameterName)
        {
          case "declaringType":
            result.DeclaringType = argument.Value as ITypeSymbol;
            result.TypeName = null;
            break;
          case "typeName":
            result.TypeName = argument.Value as string;
            result.DeclaringType = null;
            break;
          case "methodName":
            result.MethodName = argument.Value as string;
            break;
          case "methodType":
            result.MethodType = EnumName(argument);
            break;
          case "argumentTypes":
            if (!argument.IsNull)
              result.ArgumentTypes = [.. argument.Values.Select(value => value.Value).OfType<ITypeSymbol>()];
            break;
          case "argumentVariations":
            if (!argument.IsNull)
              result.ArgumentVariations = [.. argument.Values.Select(EnumName)];
            break;
        }
      }
    }

    return result.DeclaringType is null && result.TypeName is null
      ? null
      : new HarmonyTarget(result.DeclaringType, result.TypeName, result.MethodName, result.MethodType,
        result.ArgumentTypes, result.ArgumentVariations, $"Target_{patchType.Name}");
  }

  private static PatchMetadata ReadMetadata(INamedTypeSymbol patchType, IMethodSymbol method)
  {
    int? priority = null;
    ImmutableArray<string> before = default;
    ImmutableArray<string> after = default;
    foreach (var attribute in patchType.GetAttributes().Concat(method.GetAttributes()))
    {
      switch (attribute.AttributeClass?.ToDisplayString())
      {
        case "HarmonyLib.HarmonyPriority":
          if (attribute.ConstructorArguments.FirstOrDefault().Value is int value)
            priority = value;
          break;
        case "HarmonyLib.HarmonyBefore":
          before = StringValues(attribute.ConstructorArguments.FirstOrDefault());
          break;
        case "HarmonyLib.HarmonyAfter":
          after = StringValues(attribute.ConstructorArguments.FirstOrDefault());
          break;
      }
    }

    return new PatchMetadata(priority, before, after);
  }

  private static ImmutableArray<string> StringValues(TypedConstant constant)
  {
    if (constant.Kind == TypedConstantKind.Array)
      return
      [
	      .. constant.Values.Select(v => v.Value).OfType<string>()
      ];
    return constant.Value is string value ? [value] : default;
  }

  private static string? ReadReversePatchType(IMethodSymbol method)
  {
    var attribute = method.GetAttributes().FirstOrDefault(item =>
      item.AttributeClass?.ToDisplayString() == HarmonySymbolNames.HarmonyReversePatch);
    return attribute?.ConstructorArguments.Length > 0 ? EnumName(attribute.ConstructorArguments[0]) : null;
  }

  private static string EnumName(TypedConstant constant)
  {
    if (constant is { Type: INamedTypeSymbol enumType, Value: not null })
    {
      var member = enumType.GetMembers().OfType<IFieldSymbol>()
        .FirstOrDefault(field => field.HasConstantValue && Equals(field.ConstantValue, constant.Value));
      if (member is not null)
        return member.Name;
    }

    return "Normal";
  }

  private sealed class MutableTarget
  {
    public ITypeSymbol? DeclaringType;
    public string? TypeName;
    public string? MethodName;
    public string MethodType = "Normal";
    public ImmutableArray<ITypeSymbol> ArgumentTypes;
    public ImmutableArray<string> ArgumentVariations;
  }

  private static string Escape(string value) => value.Replace("\"", "\"\"");
}
